

const PAGE_CSS = '@media print{@page{size:A4;margin:14mm}.staff-roster{box-shadow:none!important;border:0!important}}'

export type RosterRow = {
  name: string
  loginId: string
  roleLabel: string
  lastLogin: string
}

export function StaffRosterDoc({
  companyName,
  teamLabel,
  generatedBy,
  generatedAt,
  rows,
}: {
  companyName: string
  teamLabel: string
  generatedBy: string
  generatedAt: string
  rows: RosterRow[]
}) {
  return (
    <div className="staff-roster mx-auto w-full max-w-[210mm] rounded-md border border-line bg-surface p-[14mm] text-ink shadow-sm print:max-w-none print:rounded-none print:p-0 print:shadow-none">
      <style>{PAGE_CSS}</style>

      <header className="flex items-start justify-between gap-6 border-b border-line-strong pb-4">
        <div>
          <div className="font-serif text-2xl font-semibold uppercase tracking-[0.18em] leading-none">
            {companyName}
          </div>
          <div className="mt-1.5 text-xs uppercase tracking-[0.2em] text-muted">Photography and Film &middot; Sydney</div>
        </div>
        <div className="text-right">
          <div className="text-xs font-bold uppercase tracking-wide text-muted">Staff roster</div>
          <div className="mt-1 text-base font-semibold">{teamLabel}</div>
          <div className="mt-1 text-xs text-ink-muted">Generated {generatedAt}</div>
        </div>
      </header>

      <h1 className="mt-6 text-lg font-semibold">
        {teamLabel} &mdash; active accounts <span className="tabular text-ink-muted">({rows.length})</span>
      </h1>

      {rows.length === 0 ? (
        <p className="mt-4 text-sm text-ink-muted">No active accounts in this team.</p>
      ) : (
        <table className="mt-4 w-full border-collapse text-sm">
          <thead>
            <tr className="border-b border-line-strong text-left text-xs uppercase tracking-wide text-muted">
              <th className="w-[8%] py-2 pr-2 font-bold">#</th>
              <th className="w-[34%] py-2 pr-2 font-bold">Name</th>
              <th className="w-[32%] py-2 pr-2 font-bold">Staff ID</th>
              <th className="w-[12%] py-2 pr-2 font-bold">Role</th>
              <th className="w-[14%] py-2 font-bold">Last sign-in</th>
            </tr>
          </thead>
          <tbody>
            {rows.map((r, i) => (
              <tr key={r.loginId} className="border-b border-line align-top">
                <td className="tabular py-2 pr-2 text-ink-muted">{i + 1}</td>
                <td className="py-2 pr-2 font-medium">{r.name}</td>
                <td className="tabular py-2 pr-2">{r.loginId}</td>
                <td className="py-2 pr-2">{r.roleLabel}</td>
                <td className="py-2 text-ink-muted">{r.lastLogin}</td>
              </tr>
            ))}
          </tbody>
        </table>
      )}

      <footer className="mt-8 border-t border-line pt-3 text-xs leading-relaxed text-muted">
        {rows.length} active account{rows.length === 1 ? '' : 's'} &middot; Generated by {generatedBy} on {generatedAt}.
        <br />
        Passwords are never shown — each is stored only as a one-way Argon2id hash and cannot be recovered.
      </footer>
    </div>
  )
}
