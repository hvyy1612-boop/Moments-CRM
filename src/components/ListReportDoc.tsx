import type { ReactNode } from 'react'

const PAGE_CSS = '@media print{@page{size:A4;margin:14mm}.list-report{box-shadow:none!important;border:0!important}}'

export type ReportColumn = { label: string; align?: 'right' }

export function ListReportDoc({
  companyName,
  title,
  columns,
  rows,
  generatedBy,
  generatedAt,
  footNote,
}: {
  companyName: string
  title: string
  columns: ReportColumn[]
  rows: ReactNode[][]
  generatedBy: string
  generatedAt: string
  footNote?: string
}) {
  return (
    <div className="list-report mx-auto w-full max-w-[210mm] rounded-md border border-line bg-surface p-[14mm] text-ink shadow-sm print:max-w-none print:rounded-none print:p-0 print:shadow-none">
      <style>{PAGE_CSS}</style>
      <header className="flex items-start justify-between gap-6 border-b border-line-strong pb-4">
        <div>
          <div className="font-serif text-2xl font-semibold uppercase tracking-[0.18em] leading-none">{companyName}</div>
          <div className="mt-1.5 text-xs uppercase tracking-[0.2em] text-muted">Photography and Film &middot; Sydney</div>
        </div>
        <div className="text-right">
          <div className="text-xs font-bold uppercase tracking-wide text-muted">{title}</div>
          <div className="mt-1 text-base font-semibold tabular">{rows.length} record{rows.length === 1 ? '' : 's'}</div>
          <div className="mt-1 text-xs text-ink-muted">Generated {generatedAt}</div>
        </div>
      </header>

      <h1 className="mt-6 text-lg font-semibold">
        {title} <span className="tabular text-ink-muted">({rows.length})</span>
      </h1>

      {rows.length === 0 ? (
        <p className="mt-4 text-sm text-ink-muted">Nothing selected.</p>
      ) : (
        <table className="mt-4 w-full border-collapse text-sm">
          <thead>
            <tr className="border-b border-line-strong text-left text-xs uppercase tracking-wide text-muted">
              <th className="w-[5%] py-2 pr-2 font-bold">#</th>
              {columns.map((c) => (
                <th key={c.label} className={`py-2 pr-2 font-bold ${c.align === 'right' ? 'text-right' : ''}`}>{c.label}</th>
              ))}
            </tr>
          </thead>
          <tbody>
            {rows.map((cells, i) => (
              <tr key={i} className="border-b border-line align-top">
                <td className="tabular py-2 pr-2 text-ink-muted">{i + 1}</td>
                {cells.map((cell, j) => (
                  <td key={j} className={`py-2 pr-2 ${columns[j]?.align === 'right' ? 'text-right tabular' : ''}`}>{cell}</td>
                ))}
              </tr>
            ))}
          </tbody>
        </table>
      )}

      <footer className="mt-8 border-t border-line pt-3 text-xs leading-relaxed text-muted">
        {footNote ? <>{footNote} &middot; </> : null}Generated by {generatedBy} on {generatedAt}.
      </footer>
    </div>
  )
}
